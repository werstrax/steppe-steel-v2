    return _art("zerno-raschet",
                "Как рассчитать зернохранилище: длина, вместимость, культуры",
                "Сколько тонн зерна вмещает 1 м длины: пшеница 67 т, горох 70 т, подсолнечник 37 т. Формула расчёта длины и примеры на 1000, 3000 и 5000 т.",
                "Сечение здания типовое, поэтому весь расчёт сводится к&nbsp;простому вопросу: сколько тонн ложится на&nbsp;один метр. Разбираем по&nbsp;шагам — с&nbsp;таблицей для пяти культур.",
                body,
                "Посчитаем зернохранилище под ваш намолот",
                "Назовите объём и культуру — инженер подберёт длину, схему секций и подготовит спецификацию.")


